// Where the host's Python lives, when PYTHONHOME does not say: an installed prefix beside the
// executable (<prefix>/bin/<host>, the cvcpkg python312 in <prefix>), else the Python the host was
// built against. "" leaves it to CPython.
std::string python_home() {
  const fs::path self = cvc::process::self_path();
  if (!self.empty()) {
    const fs::path prefix = self.parent_path().parent_path();
    std::error_code ec;
#ifdef _WIN32
    if (fs::exists(prefix / "Lib" / "os.py", ec))
      return prefix.string();
#else
    const std::string lib =
        "python" + std::to_string(PY_MAJOR_VERSION) + "." + std::to_string(PY_MINOR_VERSION);
    if (fs::exists(prefix / "lib" / lib / "os.py", ec))
      return prefix.string();
#endif
  }
#ifdef CVC_ARIADNE_PYTHON_HOME
  return CVC_ARIADNE_PYTHON_HOME;
#else
  return {};
#endif
}

// The config both boots share: the program, its home, and --python-path ahead of PYTHONPATH.
// False with `error` set.
bool configure(PyConfig &cfg, const EngineConfig &config, std::string &error) {
  cfg.install_signal_handlers = 0; // the host traps signals itself (host_signals.h)
#ifdef __EMSCRIPTEN__
  cfg.write_bytecode = 0; // the stdlib is a zip in memory: no __pycache__ to write
#endif
  const fs::path self = cvc::process::self_path();
  PyStatus st = PyConfig_SetBytesString(&cfg, &cfg.program_name,
                                        self.empty() ? config.host.c_str() : self.string().c_str());
  const std::string home = python_home();
  if (!PyStatus_Exception(st) && !home.empty() && !std::getenv("PYTHONHOME"))
    st = PyConfig_SetBytesString(&cfg, &cfg.home, home.c_str());
  std::string path;
#ifdef _WIN32
  const char sep = ';';
#else
  const char sep = ':';
#endif
  for (const std::string &p : config.path)
    path += (path.empty() ? "" : std::string(1, sep)) + p;
  if (const char *env = std::getenv("PYTHONPATH"); env && *env)
    path += (path.empty() ? "" : std::string(1, sep)) + env;
  if (!PyStatus_Exception(st) && !path.empty())
    st = PyConfig_SetBytesString(&cfg, &cfg.pythonpath_env, path.c_str());
  if (PyStatus_Exception(st)) {
    error = st.err_msg ? st.err_msg : "could not configure Python";
    return false;
  }
  return true;
}

// The document side, as the runtimes the host lends Python run it (AppRuntime::use_script_engine):
// a document's python: block at its load, and the `python.<module>` tokens.
class PythonScriptEngine : public ScriptEngine {
public:
  std::string language() const override { return "python"; }

  bool has_module(const std::string &module) const override {
    Gil gil;
    if (!g_helper)
      return false;
    PyObject *r = PyObject_CallMethod(g_helper, "has_module", "s", module.c_str());
    const bool has = r && PyObject_IsTrue(r) == 1;
    Py_XDECREF(r);
    PyErr_Clear();
    return has;
  }

  // The block runs in a module of the document's own, and its exports become host functions on
  // the runtime _arihost lends (pycvc.host_function): the lane's own registry.
  void load_block(const ScriptBlock &block, ScriptLane &,
                  std::vector<std::string> &warnings) override {
    Gil gil;
    PyObject *py_block = to_python(block.content);
    PyObject *reg = py_block ? PyObject_CallMethod(g_helper, "pycvc_register", nullptr) : nullptr;
    PyObject *result = reg ? PyObject_CallMethod(g_helper, "load_document", "OsO", py_block,
                                                 block.document.c_str(), reg)
                           : nullptr;
    Py_XDECREF(reg);
    Py_XDECREF(py_block);
    if (!result)
      throw std::runtime_error("python: " + take_error());
    if (PyList_Check(result))
      for (Py_ssize_t i = 0; i < PyList_Size(result); ++i)
        if (const char *w = PyUnicode_AsUTF8(PyList_GetItem(result, i)))
          warnings.push_back(w);
    PyErr_Clear();
    Py_DECREF(result);
  }
};

// The engine, registered while the interpreter is up.
std::shared_ptr<PythonScriptEngine> &script_engine() {
  static std::shared_ptr<PythonScriptEngine> e;
  return e;
}

#ifdef CVC_ARIADNE_PYTHON_SERVER
// A server document's load hook in arisrvx: its python: block is refused, not run. Its functions
// would be called from the document's programs, which run on the relay's loop (§6.2).
void refuse_python_block(LoadResult &lr, const std::string &) {
  for (const auto &[key, value] : lr.extras)
    if (key == "python")
      throw std::runtime_error(
          "python: a server document's python: block does not run in arisrvx yet: its functions "
          "would run on the relay's loop. Run the operator's Python beside the relay instead, "
          "with arisrvx --python main.py");
}

// pycvc.ariadne, built in (ariadne_server.py): imported at boot, so the program's
// `from pycvc.ariadne import Host` finds this host's own, whatever pycvc is installed beside it.
// False with `error` set.
bool boot_server_module(std::string &error) {
  PyObject *code =
      Py_CompileString(kAriadneServerSource, "pycvc/ariadne.py (built in)", Py_file_input);
  PyObject *mod = code ? PyImport_ExecCodeModule("pycvc.ariadne", code) : nullptr;
  Py_XDECREF(code);
  PyObject *r = mod ? PyObject_CallMethod(mod, "_install_parent", nullptr) : nullptr;
  Py_XDECREF(mod);
  if (!r) {
    error = "pycvc.ariadne did not load: " + take_error();
    return false;
  }
  Py_DECREF(r);
  return true;
}
#endif

