int Engine::serve(const std::string &path, const std::vector<std::string> &args,
                  const ServeOptions &options) {
#ifdef CVC_ARIADNE_PYTHON_SERVER
  if (!ok_ || !config_.server) {
    std::fprintf(stderr, "%s: %s\n", config_.host.c_str(),
                 ok_ ? "this engine is not a server host's" : error_.c_str());
    return 1;
  }
  Gil gil;
  PyObject *mod = PyImport_ImportModule("pycvc.ariadne");
  PyObject *py_path = PyUnicode_DecodeFSDefault(path.c_str());
  PyObject *argv = PyList_New(0);
  for (std::size_t i = 0; argv && i < args.size(); ++i) {
    PyObject *s = PyUnicode_DecodeFSDefault(args[i].c_str());
    if (!s || PyList_Append(argv, s) != 0)
      Py_CLEAR(argv);
    Py_XDECREF(s);
  }
  PyObject *ports = PyList_New(0);
  for (std::size_t i = 0; ports && i < options.ports.size(); ++i) {
    PyObject *p =
        Py_BuildValue("(ss)", options.ports[i].first.c_str(), options.ports[i].second.c_str());
    if (!p || PyList_Append(ports, p) != 0)
      Py_CLEAR(ports);
    Py_XDECREF(p);
  }
  PyObject *opts =
      ports
          ? Py_BuildValue("{s:s,s:d,s:O,s:O,s:d,s:l,s:d,s:d}", "http_listen",
                          options.http_listen.c_str(), "shutdown_timeout", options.shutdown_timeout,
                          "check", options.check ? Py_True : Py_False, "ports", ports, "slow_ms",
                          options.slow_ms, "call_concurrency", options.call_concurrency,
                          "call_rate", options.call_rate, "auth_timeout", options.auth_timeout)
          : nullptr;
  PyObject *r = mod && py_path && argv && opts
                    ? PyObject_CallMethod(mod, "_serve_program", "OOO", py_path, argv, opts)
                    : nullptr;
  Py_XDECREF(opts);
  Py_XDECREF(ports);
  Py_XDECREF(argv);
  Py_XDECREF(py_path);
  Py_XDECREF(mod);
  if (!r)
    return exit_status_from_error();
  const long status = PyLong_AsLong(r);
  Py_DECREF(r);
  if (PyErr_Occurred()) {
    PyErr_Print();
    return 1;
  }
  return static_cast<int>(status);
#else
  (void)path;
  (void)args;
  (void)options;
  std::fprintf(stderr, "%s: this host serves no Python program (arisrvx does)\n",
               config_.host.c_str());
  return 1;
#endif
}

int Engine::python_main(const EngineConfig &config, const std::vector<std::string> &args) {
  lent().host = config.host;
  std::string error;
  if (!register_builtins(error)) {
    std::fprintf(stderr, "%s: %s\n", config.host.c_str(), error.c_str());
    return 1;
  }
  PyConfig cfg;
  PyConfig_InitPythonConfig(&cfg);
  std::vector<std::string> argv{config.host + " python"};
  argv.insert(argv.end(), args.begin(), args.end());
  std::vector<char *> raw;
  for (std::string &a : argv)
    raw.push_back(a.data());
  PyStatus st = PyConfig_SetBytesArgv(&cfg, static_cast<Py_ssize_t>(raw.size()), raw.data());
  if (!PyStatus_Exception(st) && configure(cfg, config, error))
    st = Py_InitializeFromConfig(&cfg);
  else if (!PyStatus_Exception(st))
    st = PyStatus_Error(error.c_str());
  PyConfig_Clear(&cfg);
  if (PyStatus_Exception(st)) {
    if (PyStatus_IsExit(st))
      return st.exitcode;
    std::fprintf(stderr, "%s: Python failed to start: %s\n", config.host.c_str(),
                 st.err_msg ? st.err_msg : "unknown");
    return 1;
  }
  return Py_RunMain();
}

